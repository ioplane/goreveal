func TestRecoverNonGoELFIsUnavailable(t *testing.T) {
	t.Parallel()

	_, err := Recover("/bin/sh")
	if !errors.Is(err, recoveryerr.ErrUnavailable) {
		t.Fatalf("Recover(/bin/sh) error = %v, want unavailable", err)
	}
}

func containsFunction(funcs []Function, want string) bool {
	for _, fn := range funcs {
		if fn.Name == want && fn.Entry != 0 {
			return true
		}
	}
	return false
}

func findFunction(funcs []Function, want string) (Function, bool) {
	for _, fn := range funcs {
		if fn.Name == want {
			return fn, true
		}
	}

	return Function{}, false
}
